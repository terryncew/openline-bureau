"""OPENLINE-AUTONOMY-001 owner dashboard: static HTML snapshot.

Regenerated by the coordinator after every cycle from state.json and the
receipts directory. Read-only: it inspects, never controls. The owner
revokes with the coordinator's --revoke command, not through this page.
"""

from __future__ import annotations

import json
from html import escape
from pathlib import Path


def _html(value):
    """Treat every snapshot value, including worker failure notes, as text."""
    return escape(str(value), quote=True)


def render(state_dir: Path, mission: dict, queue: dict, state: dict):
    receipts = []
    rdir = state_dir / "receipts"
    if rdir.exists():
        for p in sorted(rdir.glob("*.json")):
            try:
                receipts.append(json.loads(p.read_text()))
            except ValueError:
                continue
    receipts = receipts[-20:][::-1]

    rows = []
    for tid, t in queue.items():
        st = state["tasks"].get(tid, {}).get("status", "pending")
        status_class = st if st in {
            "accepted", "rejected", "quarantined", "held", "pending"
        } else ""
        rows.append(
            f"<tr><td><code>{_html(tid)}</code></td><td>{_html(t['title'])}</td>"
            f"<td>{_html(t['change_class'])}</td>"
            f"<td class='{status_class}'>{_html(st)}</td></tr>")

    recs = []
    for r in receipts:
        auto = (r.get("extensions") or {}).get("autonomy", {})
        recs.append(
            f"<li><code>{_html(r['receipt_id'])}</code> "
            f"{_html(auto.get('kind', '?'))}/{_html(r['decision']['outcome'])} — "
            f"{_html(str(r['decision']['reason'])[:110])} "
            f"<em>({_html(r['timestamp'])})</em></li>")

    current = state.get("current")
    cur = (f"{current['task_id']} @ {current['phase']} "
           f"({current['worker_id']})" if current else "idle")

    html = f"""<!doctype html><html><head><meta charset="utf-8">
<title>Autonomy-001 · Mission dashboard</title>
<style>
body{{font-family:system-ui,sans-serif;max-width:900px;margin:0 auto;padding:1rem}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #ccc;padding:.3rem .6rem;font-size:.85rem}}
.accepted{{color:#0a6b2a}}.rejected,.quarantined{{color:#a00}}.held{{color:#8a5a00}}.pending{{color:#555}}
code{{font-size:.8rem}}li{{font-size:.85rem;margin:.25rem 0}}
</style></head><body>
<h1>Mission dashboard <small>(read-only snapshot)</small></h1>
<p><strong>Mission:</strong> {_html(str(mission['mission'])[:160])}…</p>
<p><strong>Status:</strong> {_html(cur)} · cycles completed: {_html(state['cycles_completed'])}
· revoked: {_html(mission.get('revoked'))}</p>
<h2>Work queue</h2>
<table><tr><th>Task</th><th>Title</th><th>Class</th><th>Status</th></tr>
{''.join(rows)}</table>
<h2>Recent receipts</h2><ul>{''.join(recs) or '<li>none yet</li>'}</ul>
<p><em>To revoke: run <code>python3 coordinator.py --state-dir &lt;state-dir&gt; --revoke</code>
(owner only). This page never controls the loop.</em></p>
</body></html>"""
    (state_dir / "dashboard.html").write_text(html)
